import assert from 'node:assert/strict';
import {chmod, mkdir, rm, symlink, writeFile} from 'node:fs/promises';
import {join} from 'node:path';
import {createCoreModule} from '../src/core/core.js';
import {edgeConfig, it, run, stateDir} from './support.js';
import {readApartmentContent} from '../src/apartment/content.js';
import {MAX_APARTMENT_IMAGE_BYTES} from '../src/apartment-model.js';
import {syntheticApartment, syntheticApartmentArtwork} from './fixtures/apartment.js';

it('core serves the prepared apartment only through authenticated content', async context => {
  const directory = await stateDir(context);
  const reader = {id:'apartment-reader', source:'bunny/parts/apartment-reader', token:'synthetic-apartment-reader-token', scopes:['read' as const]};
  const files = await edgeConfig(context, [reader]);
  const {runtime} = await run(context, {modules:[createCoreModule()], stateDir:directory, configFile:files.config, edge:{schemas:{}}});
  const folder = join(directory, 'modules/core/apartment');
  await mkdir(folder, {recursive:true, mode:0o700});
  const {image,bytes} = syntheticApartmentArtwork();
  const model = syntheticApartment(image);
  await mkdir(join(folder,'assets'),{mode:0o700});
  const asset = join(folder,'assets',image.id+'.png');
  await writeFile(asset,bytes,{mode:0o600});
  await writeFile(join(folder,'active.json'), JSON.stringify(model), {mode:0o600});
  const url = runtime.url + '/modules/core/content/apartment-model';
  assert.equal((await fetch(url)).status, 401);
  const response = await fetch(url, {headers:{authorization:'Bearer '+reader.token}});
  assert.equal(response.status, 200);
  assert.deepEqual(await response.json(), model);
  const authorization = {headers:{authorization:'Bearer '+reader.token}};
  const artwork = runtime.url + '/modules/core/content/apartment-art-' + image.id;
  assert.equal((await fetch(artwork)).status,401);
  const art = await fetch(artwork,authorization);
  assert.equal(art.headers.get('content-type'),'image/png');
  assert.deepEqual(Buffer.from(await art.arrayBuffer()),bytes);
  assert.equal((await fetch(artwork+'?asset=file',authorization)).status,400);
  assert.equal((await fetch(artwork.replace(image.id,'0'.repeat(64)),authorization)).status,404);
  assert.equal((await fetch(url.replace('apartment-model','apartment-art-invalid'),authorization)).status,400);
  await chmod(asset,0o644);
  assert.equal((await fetch(artwork,authorization)).status,403);
  await rm(asset);
  await symlink(join(folder,'active.json'),asset);
  assert.equal((await fetch(artwork,authorization)).status,403);
  await rm(asset);
  assert.equal((await fetch(artwork,authorization)).status,404);
  await writeFile(asset,Buffer.alloc(MAX_APARTMENT_IMAGE_BYTES+1),{mode:0o600});
  assert.equal((await fetch(artwork,authorization)).status,413);
  await writeFile(asset,'corrupt image');
  const corrupt = await fetch(artwork,authorization);
  assert.equal(corrupt.status,400);
  assert.equal((await corrupt.text()).includes(folder),false);
  assert.equal((await fetch(url,authorization)).status,200,'missing artwork does not prevent room inspection');
  const cancelled = await readApartmentContent(() => {throw new Error('do not read');},'apartment-model',AbortSignal.abort());
  assert.ok(cancelled !== undefined && 'error' in cancelled);
  assert.equal(cancelled.error.code,'cancelled');
});

import assert from 'node:assert/strict';
import {AxeBuilder} from '@axe-core/playwright';
import type {BrowserContext, Page} from 'playwright';
import type {PreferenceLibrary} from '@jimmie-potts/companions';
import {feed, type World} from './harness.ts';

/** Uses the real authenticated dashboard and its controls, with synthetic private text. */
export async function preferencesJourney(world: World, page: Page, context: BrowserContext): Promise<void> {
  await context.grantPermissions(['clipboard-read', 'clipboard-write']);
  await page.goto(`${world.url}/#/module/companions/preferences`); await feed(page, 'connected');
  const library = page.getByRole('region', {name: 'Preferences', exact: true});
  const title = library.getByRole('textbox', {name: 'Title', exact: true});
  const text = library.getByRole('textbox', {name: 'Preference text', exact: true});
  await title.fill('Synthetic preference'); await text.fill('SYNTHETIC_PREFERENCE_OLD');
  const add = library.getByRole('button', {name: 'Add preference', exact: true});
  await add.focus(); await add.press('Enter');
  const entry = library.getByRole('article', {name: 'Synthetic preference', exact: true});
  await entry.getByText('SYNTHETIC_PREFERENCE_OLD', {exact: true}).waitFor();
  await entry.getByRole('checkbox', {name: 'Copy Synthetic preference', exact: true}).check();
  await library.getByRole('button', {name: 'Copy selected active preferences', exact: true}).click();
  await library.getByText('Copied 1 active preference.', {exact: true}).waitFor();
  assert.equal(await page.evaluate(() => navigator.clipboard.readText()), 'Synthetic preference\nSYNTHETIC_PREFERENCE_OLD');
  const download = page.waitForEvent('download');
  await library.getByRole('button', {name: 'Export library', exact: true}).click();
  const stream = await (await download).createReadStream();
  const chunks: Buffer[] = []; for await (const chunk of stream) chunks.push(Buffer.from(chunk as Uint8Array));
  const exported = JSON.parse(Buffer.concat(chunks).toString()) as PreferenceLibrary;
  assert.equal(exported.schema, 'preference-library/1.0'); assert.equal(exported.entries.length, 1);
  await entry.getByRole('button', {name: 'Stop using', exact: true}).click();
  await entry.getByText('Inactive', {exact: true}).waitFor();
  await page.evaluate(() => navigator.clipboard.writeText('SYNTHETIC_CLIPBOARD_SENTINEL'));
  await library.getByRole('button', {name: 'Copy selected active preferences', exact: true}).click();
  await library.getByText('No selected preferences are currently active.', {exact: true}).waitFor();
  assert.equal(await page.evaluate(() => navigator.clipboard.readText()), 'SYNTHETIC_CLIPBOARD_SENTINEL');
  await entry.getByRole('button', {name: 'Edit', exact: true}).click();
  await text.fill('SYNTHETIC_PREFERENCE_CURRENT');
  await library.getByRole('button', {name: 'Save changes', exact: true}).click();
  await entry.getByText('SYNTHETIC_PREFERENCE_CURRENT', {exact: true}).waitFor();
  await world.restart(); await page.reload(); await feed(page, 'connected');
  await entry.getByText('Inactive', {exact: true}).waitFor();
  await entry.getByText('History', {exact: true}).click();
  await entry.getByRole('list', {name: 'Preference history'}).getByText('SYNTHETIC_PREFERENCE_OLD', {exact: true}).first().waitFor();
  assert.equal(await entry.getByRole('checkbox', {name: 'Copy Synthetic preference', exact: true}).isDisabled(), true);
  const extra = structuredClone(exported.entries[0]); assert.ok(extra);
  extra.id = 'synthetic-imported'; extra.title = 'Imported preference'; extra.text = 'SYNTHETIC_PREFERENCE_IMPORTED';
  for (const event of extra.history) {event.title = extra.title; event.text = extra.text;}
  const file = {...exported, entries: [...exported.entries, extra]};
  const upload = library.getByLabel('Import file', {exact: true});
  await upload.setInputFiles({name: 'preferences.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(file))});
  const importButton = library.getByRole('button', {name: 'Import missing preferences', exact: true});
  await importButton.click();
  const imported = library.getByRole('article', {name: 'Imported preference', exact: true});
  await imported.getByText('Inactive', {exact: true}).waitFor();
  await entry.getByText('Inactive', {exact: true}).waitFor(); await entry.getByText('SYNTHETIC_PREFERENCE_CURRENT', {exact: true}).first().waitFor();
  await importButton.click();
  await page.reload(); await feed(page, 'connected');
  await imported.getByText('Inactive', {exact: true}).waitFor();
  assert.equal(await library.getByRole('article').count(), 2);
  await entry.getByRole('button', {name: 'Reactivate', exact: true}).click(); await entry.getByText('Active', {exact: true}).waitFor();
  await entry.getByRole('checkbox', {name: 'Copy Synthetic preference', exact: true}).check();
  await library.getByRole('button', {name: 'Copy selected active preferences', exact: true}).click();
  await library.getByText('Copied 1 active preference.', {exact: true}).waitFor();
  const copied = await page.evaluate(() => navigator.clipboard.readText());
  assert.equal(copied, 'Synthetic preference\nSYNTHETIC_PREFERENCE_CURRENT');
  assert.equal(copied.includes('OLD') || copied.includes('IMPORTED'), false);
  assert.deepEqual((await new AxeBuilder({page}).include('main').withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations.map(value => value.id), []);
  await page.setViewportSize({width: 390, height: 844});
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), true);
  await title.fill('Unsent draft'); await text.fill('UNSENT_PREFERENCE_DRAFT');
  await context.setOffline(true); world.dropDashboardStreams();
  await library.getByText('Disconnected. Saved preferences may be out of date.', {exact: true}).waitFor();
  assert.equal(await add.isDisabled(), true); assert.equal(await text.inputValue(), 'UNSENT_PREFERENCE_DRAFT');
  await context.setOffline(false); await page.reload(); await feed(page, 'connected');
  await page.route('**/api/v2/authority?scope=control', route => route.fulfill({status: 403, contentType: 'application/json', body: '{"error":{"code":"forbidden","retryable":false}}'}));
  await page.reload(); await feed(page, 'connected');
  await library.getByText('Read-only access. Controls require operator authority.', {exact: true}).waitFor();
  assert.equal(await add.isDisabled(), true); assert.equal(await importButton.isDisabled(), true);
  await page.unroute('**/api/v2/authority?scope=control');
  await page.reload(); await feed(page, 'connected');
  await library.getByText('Read-only access. Controls require operator authority.', {exact: true}).waitFor({state: 'hidden'});
  await page.setViewportSize({width: 1280, height: 1000});
  assert.equal(JSON.stringify(world.logs).includes('SYNTHETIC_PREFERENCE_'), false);
}

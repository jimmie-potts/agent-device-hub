import assert from 'node:assert/strict';
import {AxeBuilder} from '@axe-core/playwright';
import type {BrowserContext, Page} from 'playwright';
import type {World} from './harness.ts';
import {feed} from './harness.ts';
import {turnStarted} from '../../dist/tests/fixtures/agents.js';

/** Called by the existing hosted companions journey after its coding turn ends. */
export async function suggestionsJourney(world: World, page: Page, context: BrowserContext): Promise<void> {
  const form = page.getByRole('region', {name: 'Coding suggestions', exact: true});
  await form.getByRole('combobox', {name: 'Coding session', exact: true}).selectOption({label: 'claude: session-sim-1 (host-sim/claude-code)'});
  await form.getByText('Session context changed. Supply results for the current session revision.', {exact: true}).waitFor();
  const bodies: string[] = [];
  page.on('request', request => {if (request.method() !== 'GET') bodies.push(request.postData() ?? '');});
  const fill = async (task = 'SYNTHETIC1098_TASK'): Promise<void> => {
    await form.getByRole('textbox', {name: 'Task ID', exact: true}).fill(task);
    await form.getByRole('textbox', {name: 'Repository reference (optional)', exact: true}).fill('SYNTHETIC1098_REPOSITORY');
    await form.getByRole('textbox', {name: 'Current head commit', exact: true}).fill('a'.repeat(40));
    await form.getByRole('textbox', {name: 'Evidence head commit', exact: true}).fill('a'.repeat(40));
    await form.getByRole('textbox', {name: 'Observation time (UTC ISO)', exact: true}).fill(new Date().toISOString());
    await form.getByRole('combobox', {name: 'tests status', exact: true}).selectOption('passed');
    await form.getByRole('textbox', {name: 'tests evidence reference', exact: true}).fill('SYNTHETIC1098_TEST_RECEIPT');
    await form.getByRole('combobox', {name: 'build status', exact: true}).selectOption('passed');
    await form.getByRole('textbox', {name: 'build evidence reference', exact: true}).fill('SYNTHETIC1098_BUILD_RECEIPT');
    await form.getByRole('combobox', {name: 'browser status', exact: true}).selectOption('unrun');
    await form.getByRole('textbox', {name: 'browser evidence reference', exact: true}).fill('SYNTHETIC1098_BROWSER_PLAN');
  };
  const inspect = form.getByRole('button', {name: 'Inspect coding suggestion', exact: true});
  const card = form.getByRole('article', {name: 'Coding suggestion', exact: true});
  const copy = form.getByRole('button', {name: 'Copy coding suggestion', exact: true});
  await context.grantPermissions(['clipboard-read', 'clipboard-write']);
  await page.evaluate(() => navigator.clipboard.writeText('SYNTHETIC1098_CLIPBOARD_SENTINEL'));
  await inspect.click(); await form.getByText(/Name one task/).waitFor();
  assert.equal(await card.count(), 0, 'turn-ended metadata alone cannot generate a suggestion');
  await fill(); await inspect.focus(); await inspect.press('Enter');
  await card.waitFor();
  const prompt = await card.locator('pre').innerText();
  for (const value of ['Owner-supplied', 'SYNTHETIC1098_TASK', 'claude/session-sim-1', 'tests: passed', 'browser: unrun', 'SYNTHETIC1098_TEST_RECEIPT', 'SYNTHETIC1098_BROWSER_PLAN', 'Please run the unrun browser check']) assert.ok(prompt.includes(value), value);
  assert.equal(await page.evaluate(() => navigator.clipboard.readText()), 'SYNTHETIC1098_CLIPBOARD_SENTINEL');
  await inspect.click(); assert.equal(await card.locator('pre').innerText(), prompt, 'duplicate inspection preserves the same proposal');
  await copy.focus(); await copy.press('Enter'); await form.getByText('Copied coding suggestion. Nothing was submitted.', {exact: true}).waitFor();
  assert.equal(await page.evaluate(() => navigator.clipboard.readText()), prompt);
  assert.equal(bodies.length, 0, 'inspection and copying make no HTTP write or harness call');
  assert.deepEqual((await new AxeBuilder({page}).include('main').withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations.map(value => value.id), []);
  await page.setViewportSize({width: 390, height: 844});
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), true);
  assert.deepEqual((await new AxeBuilder({page}).include('main').withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations.map(value => value.id), []);
  await page.setViewportSize({width: 1280, height: 1000});
  // New evidence supersedes the preview; older/equal-time contradictory evidence cannot restore it.
  const observed = form.getByRole('textbox', {name: 'Observation time (UTC ISO)', exact: true});
  const firstAt = await observed.inputValue();
  await observed.fill(new Date(Date.parse(firstAt) - 1).toISOString()); await inspect.click();
  await form.getByText(/Older evidence cannot replace/).waitFor(); assert.equal(await card.count(), 0);
  await observed.fill(new Date().toISOString()); await inspect.click(); await card.waitFor();
  await form.getByRole('textbox', {name: 'Evidence head commit', exact: true}).fill('b'.repeat(40));
  await observed.fill(new Date().toISOString());
  await inspect.click(); await form.getByText(/Supply matching current and evidence head/).waitFor(); assert.equal(await card.count(), 0);
  await fill(); await inspect.click(); await card.waitFor();
  const usefulAt = await observed.inputValue();
  await observed.fill(new Date().toISOString());
  await form.getByRole('combobox', {name: 'tests status', exact: true}).selectOption('unknown');
  await inspect.click(); await form.getByText(/No supported next check follows/).waitFor();
  await observed.fill(usefulAt); await inspect.click(); await form.getByText(/Older evidence cannot replace/).waitFor();
  // A new turn cannot inherit the old form's checks.
  await world.observe(turnStarted, {turn: 'suggestions-next-turn'});
  await form.getByText('Session context changed. Supply results for the current session revision.', {exact: true}).waitFor();
  assert.equal(await card.count(), 0); assert.equal(await form.getByRole('combobox', {name: 'tests status', exact: true}).inputValue(), 'unknown');
  await fill('SYNTHETIC1098_OTHER_TASK'); await inspect.click(); await card.waitFor();
  assert.ok(!(await card.innerText()).includes('SYNTHETIC1098_TASK'));
  await page.getByRole('tab', {name: 'Controls', exact: true}).click();
  const mute = page.getByRole('button', {name: 'Mute Turn endings', exact: true}); await mute.click();
  await form.getByText(/Turn endings are muted/).waitFor(); assert.equal(await card.count(), 0);
  await page.getByRole('button', {name: 'Unmute Turn endings', exact: true}).click(); await card.waitFor();
  await page.getByRole('button', {name: 'Disable Reachy text cards', exact: true}).click();
  await form.getByText(/Enable Reachy text cards to inspect/).waitFor(); assert.equal(await card.count(), 0);
  await page.getByRole('button', {name: 'Enable Reachy text cards', exact: true}).click(); await card.waitFor();
  await page.evaluate(() => {navigator.clipboard.writeText = () => Promise.reject(new DOMException('Denied', 'NotAllowedError'));});
  await copy.click(); await form.getByText(/Copy could not be confirmed/).waitFor();
  await page.clock.install({time: new Date()});
  await page.clock.fastForward(300_001);
  await form.getByText(/Evidence must have an actual observation time/).waitFor();
  assert.equal(await card.count(), 0, 'expiry retires the visible proposal without waiting for another input');
  await page.clock.setSystemTime(new Date()); await page.clock.resume();
  await context.setOffline(true); world.dropDashboardStreams();
  await form.getByText(/Coding suggestions unavailable/).waitFor(); assert.equal(await card.count(), 0);
  await context.setOffline(false); await page.reload(); await feed(page, 'connected');
  assert.equal(await card.count(), 0); assert.equal(await form.getByRole('textbox', {name: 'Task ID', exact: true}).inputValue(), '');
  assert.ok(bodies.every(body => !body.includes('SYNTHETIC1098')), 'no private evidence is sent to the runtime');
  assert.ok(!JSON.stringify(world.logs).includes('SYNTHETIC1098'), 'diagnostics contain no evidence text');
}

// Three baseline dots, outside the label alphabet like the 3x5 marker.
export const largeMarkerGlyphs:Readonly<Record<string,readonly string[]>>={'…':['.....','.....','.....','.....','.....','.....','#.#.#']};
/** Draw a bitmap given as rows ('#' lit) with its top-left corner at (x, y) on a 64×64 RGB buffer. */
export function drawBitmap(rgb:Uint8Array,rows:readonly string[],x:number,y:number,color:Color):void {
 rows.forEach((row,dy)=>{for(let dx=0;dx<row.length;dx++)if(row[dx]==='#'&&x+dx>=0&&x+dx<64&&y+dy>=0&&y+dy<64)rgb.set(color,((y+dy)*64+x+dx)*3);});
}
/** Draw 5x7 text at a 6-pixel advance; characters outside the alphabet and marker draw as '?'. */
export function drawLargeText(rgb:Uint8Array,value:string,x:number,y:number,color:Color):void {
 for(const [i,char] of Array.from(value).entries())drawBitmap(rgb,largeGlyphs[char]??largeMarkerGlyphs[char]??largeGlyphs['?']!,x+i*6,y,color);
}
